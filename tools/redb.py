"""The NX2navi reverse-engineering database: named functions, structs and globals of the game's main.

    redb.py add <kind> <name> [--addr 0x..] [--confidence low|medium|high] [--source ...] [--note ...]
    redb.py show [REGEX]
    redb.py strings <f_ADDR|0xADDR>     strings the function loads (from strxref.tsv)
    redb.py header                      C header of every function entry, for mods (build/v111/re/symbols.h)

kind: function (a lifted guest function), host (a runtime-side hook, addr empty), struct, global, tag (an MSBT
control tag, name group.type). Addresses come from the game's code, so the database lives under build/
(build/v111/re/symbols.json, one object per entry, sorted by kind then address), never in a repository.
"""

import argparse
import json
import re
import sys
from pathlib import Path

TREE = Path.home() / "claude/nx2navi/NX2navi"
RE = TREE / "build/v111/re"
DB = RE / "symbols.json"
KINDS = ("function", "host", "struct", "global", "tag")


def load():
    return json.loads(DB.read_text()) if DB.exists() else []


def save(entries):
    entries.sort(key=lambda e: (KINDS.index(e["kind"]), int(e.get("addr") or "0", 16), e["name"]))
    RE.mkdir(parents=True, exist_ok=True)
    DB.write_text(json.dumps(entries, indent=1, ensure_ascii=False) + "\n")


def cmd_add(args):
    entries = [e for e in load() if (e["kind"], e["name"]) != (args.kind, args.name)]
    entry = {"kind": args.kind, "name": args.name, "addr": args.addr or "", "confidence": args.confidence}
    entry |= {"source": args.source or "", "note": args.note or ""}
    save(entries + [entry])


def cmd_show(args):
    pattern = re.compile(args.regex or "")
    for e in load():
        line = f'{e["kind"]:8} {e["addr"]:14} {e["name"]:36} {e["confidence"]:6} {e["note"]}'
        if pattern.search(line):
            print(line)


def cmd_strings(args):
    func = args.func if args.func.startswith("f_") else f"f_{int(args.func, 16):x}"
    for line in (RE / "strxref.tsv").open():
        if line.startswith(func + "\t"):
            print(line.rstrip("\n").split("\t", 1)[1])


def cmd_header(_):
    out = ["// Generated by tools/redb.py from build/v111/re/symbols.json: guest functions by name.", "#pragma once"]
    for e in load():
        if e["kind"] == "function" and e["addr"]:
            out.append(f'#define SYM_{re.sub(r"\\W", "_", e["name"])} {e["addr"]}ull   // {e["confidence"]}')
    (RE / "symbols.h").write_text("\n".join(out) + "\n")
    print(RE / "symbols.h")


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("add")
    p.add_argument("kind", choices=KINDS)
    p.add_argument("name")
    p.add_argument("--addr")
    p.add_argument("--confidence", choices=("low", "medium", "high"), default="medium")
    p.add_argument("--source")
    p.add_argument("--note")
    sub.add_parser("show").add_argument("regex", nargs="?")
    sub.add_parser("strings").add_argument("func")
    sub.add_parser("header")
    args = ap.parse_args()
    {"add": cmd_add, "show": cmd_show, "strings": cmd_strings, "header": cmd_header}[args.cmd](args)


if __name__ == "__main__":
    sys.exit(main())
